import incident_report as ir

HERE = Path(__file__).parent
SAMPLE_EXPORTS = HERE / "data" / "exports"
SLA_HOURS = {"P1": 4, "P2": 24, "P3": 72, "P4": 168}
GENERATED_AT = datetime(2026, 10, 21, 2, 0, tzinfo=UTC)

results = {"PASS": 0, "FAIL": 0, "TODO": 0}


def check(name, test):
    """Run one check. `test` returns None on success or a string describing the failure."""
    try:
        with tempfile.TemporaryDirectory() as workdir:
            problem = test(Path(workdir))
    except NotImplementedError:
        status, detail = "TODO", "not implemented yet"
    except Exception as error:  # noqa: BLE001 - any crash in your code is a FAIL
        frame = traceback.extract_tb(error.__traceback__)[-1]
        status = "FAIL"
        detail = f"{type(error).__name__}: {error} (at {frame.filename}:{frame.lineno})"
    else:
        status, detail = ("PASS", "") if problem is None else ("FAIL", problem)
    results[status] += 1
    print(f"{status:<5} {name}" + (f"\n      {detail}" if detail else ""))


def expect(actual, expected, what="result"):
    if actual != expected:
        return f"{what} was {actual!r}\n      expected {expected!r}"
    return None


def raises(function, exception_type, *, cause=None, mentions=()):
    """Call function; check it raises exception_type, chained from `cause`, naming `mentions`."""
    try:
        function()
    except exception_type as error:
        if cause is not None and not isinstance(error.__cause__, cause):
            actual = type(error.__cause__).__name__ if error.__cause__ else "nothing"
            expected = cause.__name__
            return f"chain the original error with 'from': cause was {actual}, not {expected}"
        missing = [text for text in mentions if text not in str(error)]
        if missing:
            return f"message {str(error)!r} should mention {missing}"
        return None
    return f"no {exception_type.__name__} was raised"


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    return path


def valid_record(**changes):
    record = {
        "id": "INC-9001",
        "title": "Badge readers offline at the Zürich depot",
        "team": "it-support",
        "priority": "P2",
        "status": "open",
        "age_hours": 28,
        "assignee": None,
        "tags": ["access"],
    }
    record.update(changes)
    return record


def sample_exports(workdir):
    """A private copy of the provided export files."""
    target = workdir / "data" / "exports"
    shutil.copytree(SAMPLE_EXPORTS, target)
    return target


# ---------------------------------------------------------------- load_config
CONFIG = {
    "input_dir": "data/exports",
    "output_file": "out/report.json",
    "sla_hours": SLA_HOURS,
}


def test_config_valid(workdir):
    path = write_json(workdir / "settings" / "config.json", CONFIG)
    config = ir.load_config(path)
    return expect(
        config,
        {
            "input_dir": workdir / "settings" / "data" / "exports",
            "output_file": workdir / "settings" / "out" / "report.json",
            "sla_hours": SLA_HOURS,
        },
        "config (paths must be relative to the config file's folder)",
    )


def test_config_missing_or_malformed(workdir):
    missing = workdir / "missing.json"
    problem = raises(
        lambda: ir.load_config(missing),
        ir.ConfigError,
        cause=FileNotFoundError,
        mentions=["missing.json"],
    )
    broken = workdir / "broken.json"
    broken.write_text('{"input_dir": "data",\n "sla_hours": }', encoding="utf-8")
    return problem or raises(
        lambda: ir.load_config(broken),
        ir.ConfigError,
        cause=json.JSONDecodeError,
        mentions=["broken.json"],
    )


def test_config_missing_key(workdir):
    config = {key: value for key, value in CONFIG.items() if key != "sla_hours"}
    path = write_json(workdir / "config.json", config)
    return raises(lambda: ir.load_config(path), ir.ConfigError, mentions=["sla_hours"])


def test_config_bad_values(workdir):
    cases = {
        "top level is a list": [CONFIG],
        "output_file is a number": CONFIG | {"output_file": 7},
        "sla_hours has a string": CONFIG | {"sla_hours": {"P1": "4"}},
        "sla_hours has zero": CONFIG | {"sla_hours": {"P1": 0}},
        "sla_hours has true": CONFIG | {"sla_hours": {"P1": True}},
        "sla_hours is a list": CONFIG | {"sla_hours": [4, 24]},
    }
    for label, data in cases.items():
        path = write_json(workdir / "config.json", data)
        problem = raises(lambda path=path: ir.load_config(path), ir.ConfigError)
        if problem:
            return f"{label}: {problem}"
    return None


