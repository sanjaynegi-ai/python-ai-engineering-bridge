"""Acceptance checks for the Session 03 workbook.

Run from your project folder:

    uv run check_report.py

Each check prints PASS, FAIL or TODO (the function still raises NotImplementedError).
The exit code is 0 only when every check passes. Checks work on temporary copies
of the data, so your config.json and data/ folder are never changed.

Do not edit this file. If a check looks wrong, re-read the requirement in the
workbook and the function's docstring first.
"""

import contextlib
