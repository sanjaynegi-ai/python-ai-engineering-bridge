"""Acceptance checks for the Session 02 workbook.

Run from your project folder:

    uv run check_summary.py

Each check prints PASS, FAIL or TODO (the function still raises NotImplementedError).
The exit code is 0 only when every check passes.

Do not edit this file. If a check looks wrong, re-read the requirement in the
workbook and the function's docstring first.
"""

import contextlib
import copy
import io
import sys
import traceback

import ticket_summary as ts
from sample_tickets import SLA_HOURS, TICKETS

results = {"PASS": 0, "FAIL": 0, "TODO": 0}


def check(name, test):
    """Run one check. `test` returns None on success or a string describing the failure."""
    try:
        problem = test()
    except NotImplementedError:
        status, detail = "TODO", "not implemented yet"
    except Exception as error:  # noqa: BLE001 - any crash in your code is a FAIL
        frame = traceback.extract_tb(error.__traceback__)[-1]
        status = "FAIL"
        detail = f"{type(error).__name__}: {error} (at {frame.filename}:{frame.lineno})"
    else:
        status, detail = ("PASS", "") if problem is None else ("FAIL", problem)
    results[status] += 1
    print(f"{status:<5} {name}" + (f"\n      {detail}" if detail else ""))


def expect(actual, expected, what="result"):
    if actual != expected:
        return f"{what} was {actual!r}\n      expected {expected!r}"
    return None


def unchanged(original, after, what="the input"):
    if original != after:
        return (
            f"{what} was modified; your function must not change the data it is given"
        )
    return None


def raw_ticket(ticket_id):
    """A private copy of the first raw record with this id."""
    return copy.deepcopy(next(t for t in TICKETS if t["id"] == ticket_id))


def prepared_tickets():
    """Normalise and deduplicate with YOUR functions, as main() will."""
    return ts.deduplicate(
        [ts.normalise_ticket(ticket) for ticket in copy.deepcopy(TICKETS)]
    )


# ---------------------------------------------------------------- normalise_ticket
def test_normalise_values():
    raw = raw_ticket("INC-2003")
    return expect(
        ts.normalise_ticket(raw),
        {
            "id": "INC-2003",
            "title": "VPN drops for the Berlin office",
            "team": "network",
            "priority": "P2",
            "status": "in_progress",
            "age_hours": 12,
            "assignee": "li",
            "tags": ["network", "vpn"],
        },
    )


def test_normalise_blank_assignee():
    blank = ts.normalise_ticket(raw_ticket("INC-2006"))["assignee"]  # "  "
    empty = ts.normalise_ticket(raw_ticket("INC-2013"))["assignee"]  # ""
    missing = ts.normalise_ticket(raw_ticket("INC-2002"))["assignee"]  # None
    return expect(
        [blank, empty, missing], [None, None, None], "assignees for '  ', '' and None"
    )


def test_normalise_tag_case():
    return expect(
        ts.normalise_ticket(raw_ticket("INC-2001"))["tags"], ["api", "network"], "tags"
    )


def test_normalise_does_not_mutate():
    raw = raw_ticket("INC-2003")
    before = copy.deepcopy(raw)
    result = ts.normalise_ticket(raw)
    if result is raw:
        return "returned the same dict object it was given; build a new dict"
    if result["tags"] is raw["tags"]:
        return "the returned ticket shares its tags list with the input"
    return unchanged(before, raw)


# ---------------------------------------------------------------- deduplicate
def test_deduplicate_keeps_first():
    tickets = [ts.normalise_ticket(t) for t in copy.deepcopy(TICKETS)]
    result = ts.deduplicate(tickets)
    problem = expect(len(result), 14, "number of unique tickets")
    if problem:
        return problem
    first_2006 = next(t for t in result if t["id"] == "INC-2006")
    return expect(first_2006["age_hours"], 26, "age_hours of the INC-2006 you kept")


def test_deduplicate_order_and_input():
    tickets = [ts.normalise_ticket(t) for t in copy.deepcopy(TICKETS)]
    before = copy.deepcopy(tickets)
    ids = [t["id"] for t in ts.deduplicate(tickets)]
    problem = expect(ids, [f"INC-{n}" for n in range(2001, 2015)], "ticket id order")
    return problem or unchanged(before, tickets)


# ---------------------------------------------------------------- is_open / is_breached
def test_is_open():
    statuses = ["open", "in_progress", "resolved", "closed"]
    actual = [ts.is_open({"status": status}) for status in statuses]
    return expect(
        actual,
        [True, True, False, False],
        "is_open for open/in_progress/resolved/closed",
    )


def test_is_breached():
    cases = [
        ({"status": "open", "priority": "P2", "age_hours": 25}, True),
        (
            {"status": "open", "priority": "P2", "age_hours": 24},
            False,
        ),  # exactly at the limit
        (
            {"status": "closed", "priority": "P1", "age_hours": 500},
            False,
        ),  # closed never breaches
    ]
    actual = [ts.is_breached(ticket, SLA_HOURS) for ticket, _ in cases]
    return expect(
        actual, [want for _, want in cases], "is_breached for 25h, 24h, closed"
    )


# ---------------------------------------------------------------- count_by / group_by_team
def test_count_by():
    tickets = prepared_tickets()
    before = copy.deepcopy(tickets)
    problem = expect(
        ts.count_by(tickets, "priority"),
        {"P1": 4, "P2": 5, "P3": 3, "P4": 2},
        "count_by priority",
    )
    problem = problem or expect(
        ts.count_by(tickets, "status"),
        {"open": 9, "in_progress": 2, "resolved": 2, "closed": 1},
        "count_by status",
    )
    return problem or unchanged(before, tickets)


