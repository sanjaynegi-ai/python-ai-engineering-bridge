def test_top_tags_tie_break():
    tickets = [
        {"tags": ["zeta"]},
        {"tags": ["alpha", "zeta"]},
        {"tags": ["beta", "alpha"]},
    ]
    return expect(
        ts.top_tags(tickets, 2), [("alpha", 2), ("zeta", 2)], "top_tags with a tie"
    )


def test_top_tags_short():
    return expect(
        ts.top_tags([{"tags": ["dns"]}], 5), [("dns", 1)], "top_tags when n > tags"
    )


# ---------------------------------------------------------------- main
def test_main_report():
    output = io.StringIO()
    with contextlib.redirect_stdout(output):
        ts.main()
    text = output.getvalue()
    expected_fragments = [
        "16 exported, 14 unique, 11 open",
        "INC-2007",
        "INC-2009",
        "latency (3)",
    ]
    missing = [fragment for fragment in expected_fragments if fragment not in text]
    if missing:
        return f"the report is missing {missing}; compare it with the example in the workbook"
    oldest_first = [
        "INC-2007",
        "INC-2004",
        "INC-2002",
        "INC-2001",
    ]  # 200h, 80h, 30h, 7h
    positions = [text.find(ticket_id) for ticket_id in oldest_first]
    if -1 in positions or positions != sorted(positions):
        return (
            f"breaches should be listed oldest first: {' before '.join(oldest_first)}"
        )
    return None


CHECKS = [
    ("normalise_ticket cleans team, status, assignee and tags", test_normalise_values),
    ("normalise_ticket turns blank assignees into None", test_normalise_blank_assignee),
    ("normalise_ticket lower-cases tags", test_normalise_tag_case),
    ("normalise_ticket does not modify its input", test_normalise_does_not_mutate),
    ("deduplicate keeps the first occurrence", test_deduplicate_keeps_first),
    ("deduplicate preserves order and its input", test_deduplicate_order_and_input),
    ("is_open", test_is_open),
    ("is_breached, including the exact-limit case", test_is_breached),
    ("count_by", test_count_by),
    ("group_by_team", test_group_by_team),
    ("team_summary", test_team_summary),
    ("team_summary for a team with nothing open", test_team_summary_no_open_tickets),
    ("top_tags", test_top_tags),
    ("top_tags breaks ties alphabetically", test_top_tags_tie_break),
    ("top_tags when there are fewer tags than n", test_top_tags_short),
    ("main prints the report", test_main_report),
]

if __name__ == "__main__":
    for check_name, check_function in CHECKS:
        check(check_name, check_function)
    passed, failed, todo = results["PASS"], results["FAIL"], results["TODO"]
    print(f"\nPassed: {passed}  Failed: {failed}  Not implemented: {todo}")
    sys.exit(0 if results["PASS"] == len(CHECKS) else 1)
